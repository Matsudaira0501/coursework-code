def compute_log_prior_p(
    y: "np.ndarray[int]",
) -> "np.ndarray[float]":
    """二値（0 or 1）の配列から各事象の事前確率を計算し，その対数を返す．

    >>> y = np.array([0, 0, 1, 1, 0])
    >>> expected = np.array([-0.51082562, -0.91629073])
    >>> np.allclose(compute_log_prior_p(y), expected)
    True
    """
    res = []
    ct = 0
    for i in range(len(y)):
      if y[i] == 0:
         ct += 1
    res.append(np.log(ct/len(y)))
    res.append(np.log((len(y)-ct)/len(y)))
    return np.array(res)


