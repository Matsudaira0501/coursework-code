class MyBayes:
    def __init__(self):
        """
        >>> X = np.array([[3, 4, 0, 1],
        ...               [5, 4, 1, 0],
        ...               [3, 3, 4, 2],
        ...               [3, 2, 3, 4],
        ...               [2, 3, 0, 0]], dtype=float)
        >>> y = np.array([0, 0, 1, 1, 0])
        >>> model = MyBayes()
        >>> model.fit(X, y)
        >>> model.predict(X)
        array([0, 0, 1, 1, 0])
        """
        self.log_prior_p = None
        self.log_post_P = None

    def fit(
        self,
        X_train: "np.ndarray[np.ndarray[float]]",
        y_train: "np.ndarray[int]",
    ) -> None:
        """各クラスの事前確率の対数および各ワードの事後確率の対数を計算し，保持する．"""

        self.log_prior_p = compute_log_prior_p(y_train)
        self.log_post_P = compute_log_post_P(X_train, y_train)
    def predict(
        self,
        X_test: "np.ndarray[np.ndarray[float]]",
    ) -> "np.ndarray[int]":
        """単純ベイズ分類器により各特徴ベクトルが属するクラスを予測し，返す．"""

        ans = compute_likelihoods(X_test, self.log_prior_p, self.log_post_P)
        res = []

        for i in range(len(ans)):
          m = 0
          a = ans[i][0]
          for j in range(len(ans[0])):
            if a < ans[i][j]:
              a = ans[i][j]
              m = j
          res.append(m)
        return np.array(res)


