def compute_likelihoods(
    X: "np.ndarray[np.ndarray[float]]",
    log_prior_p: "np.ndarray[float]",
    log_post_P: "np.ndarray[np.ndarray[float]]",
) -> "np.ndarray[np.ndarray[float]]":
    """Bag-of-Wordsの配列から各クラスの尤度を計算し，返す．

    >>> X = np.array([[3, 4, 0, 1],
    ...               [5, 4, 1, 0],
    ...               [3, 3, 4, 2],
    ...               [3, 2, 3, 4],
    ...               [2, 3, 0, 0]], dtype=float)
    >>> log_prior_p = np.array([-0.51082562, -0.91629073])
    >>> log_post_P = np.array(
    ...     [[-0.89794159, -0.81093022, -2.60268969, -2.60268969],
    ...      [-1.38629436, -1.54044504, -1.25276297, -1.38629436]]
    ... )
    >>> expected = np.array([[-9.05106096, -12.62324833],
    ...                      [-10.84694414, -15.26230566],
    ...                      [-21.25357919, -17.48014953],
    ...                      [-23.04533866, -17.45953024],
    ...                      [-4.73949946, -8.31021457]])
    >>> np.allclose(compute_likelihoods(X, log_prior_p, log_post_P), expected)
    True
    """
    res = []
    for i in range(len(X)):
      PL = []
      for j in range(len(log_prior_p)):
        P = 0
        for k in range(len(X[0])):
          P += X[i][k] * log_post_P[j][k]
        P += log_prior_p[j]
        PL.append(P)
      res.append(PL)
    return np.array(res)


