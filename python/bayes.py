def compute_log_post_P(
    X: "np.ndarray[np.ndarray[float]]",
    y: "np.ndarray[int]",
) -> "np.ndarray[np.ndarray[float]]":
    """Bag-of-Wordsの配列から各クラス（0 or 1）における事後確率を計算し，その対数を返す．

    >>> X = np.array([[3, 4, 0, 1],
    ...               [5, 4, 1, 0],
    ...               [3, 3, 4, 2],
    ...               [3, 2, 3, 4],
    ...               [2, 3, 0, 0]], dtype=float)
    >>> y = np.array([0, 0, 1, 1, 0])
    >>> expected = np.array(
    ...     [[-0.89794159, -0.81093022, -2.60268969, -2.60268969],
    ...      [-1.38629436, -1.54044504, -1.25276297, -1.38629436]]
    ... )
    >>> np.allclose(compute_log_post_P(X, y), expected)
    True
    """
    W = len(X[0])
    res = []
    n_0 = 0
    m_0 = []
    n_1 = 0
    m_1 = []
    for i in range(W):
      m_0.append(0)
      m_1.append(0)

    for i in range(len(X)):
      if y[i] == 0:
        n_0 += np.sum(X[i])
        m_0 += X[i]
      else:
        n_1 += np.sum(X[i])
        m_1 += X[i]

    zero = []
    one = []
    for i in range(W):
      zero.append(np.log((m_0[i]+1)/ (n_0+W)))
      one.append(np.log((m_1[i]+1)/ (n_1+W)))

    res.append(zero)
    res.append(one)
    return np.array(res)


