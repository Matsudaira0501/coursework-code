import numpy as np


def dist(
    x_train,
    x_test,
) -> float:

    result = (x_test - x_train) @ (x_test - x_train)
    result = result ** 0.5

    return result


def get_nearest_pos(
    X_train,
    x_test,
) -> int:
    """2-2: 最近傍となる特徴ベクトルX_train[i]を見つけ，その位置iを返す．

    >>> X = np.array([[1, 2],
    ...               [0, 0],
    ...               [-1, -3]])
    >>> y = np.array([0, 0])
    >>> get_nearest_pos(X, y)
    1
    """
    d = len(X_train)
    a = dist(X_train[0], x_test)
    for i in range(d):

      if a >= dist(X_train[i], x_test):
        result = i
        a = dist(X_train[i], x_test)

    return result


class MyKNN:
    def __init__(
        self,
    ):
        """内部パラメータを初期化．このコンストラクタは修正不要．

        >>> X_train = np.array([[1, 2],
        ...                     [0, 0],
        ...                     [-1, -3]])
        >>> y_train = np.array([2, 0, 1])
        >>> X_test = np.array([[-1, -2],
        ...                     [1, 0]])
        >>> y_test = np.array([1, 0])
        >>> model = MyKNN()
        >>> model.fit(X_train, y_train)
        >>> model.predict(X_test)
        array([1, 0])
        """
        self.X_train = None
        self.y_train = None

    def fit(
        self,
        X_train,
        y_train,
    ) -> None:
        """2-3: 最近傍法のための準備（i.e., 学習）を行う．"""
        self.X_train = X_train
        self.y_train = y_train

        pass

    def predict(
        self,
        X_test,
    ) -> "np.ndarray[int]":

        """2-4: 最近傍法に基づきX_test中の各特徴ベクトルが属するクラスy_predictedを予測する．"""

        res = []
        d = len(X_test)
        for i in range(d):
          res.append(self.y_train[get_nearest_pos(self.X_train, X_test[i])])

        return np.array(res)

    def get_parameters(
        self,
    ):
        """テスト用に内部パラメータを出力．この関数は修正不要．"""
        return self.X_train, self.y_train


