import numpy as np


def extend(
    X: "np.ndarray[np.ndarray[float]]",
) -> "np.ndarray[np.ndarray[float]]":
    """与えられたd次元特徴ベクトルの配列をd+1次元の拡張特徴ベクトルの配列へ変換し返す．"""
    one = np.ones((len(X), 1))
    return np.hstack((one, X))


def to_one_hot(
    y: "np.ndarray[int]",
    class_num: int,
) -> "np.ndarray[np.ndarray[int]]":
    """与えられた教師信号の配列をone-hot表現に変換し，返す．"""
    return np.identity(class_num)[y]


def sigmoid(
    h: "np.ndarray",
) -> "np.ndarray":
    """与えられた多次元配列の各要素をシグモイド関数へ通した結果を返す．"""
    return 1 / (1 + np.exp(-h))


class MyMLP:
    def __init__(
        self,
        rho: float = 1,
        hidden_unit_size: int = 4,
        loss_threshold: float = 0.01,
        random_seed: int = 123,
    ):
        self.rho = rho
        self.loss_threshold = loss_threshold
        self.hidden_unit_size = hidden_unit_size
        self.random_seed = random_seed
        self.W_AB = None
        self.W_BC = None

    @classmethod
    def g(
        cls,
        x: "np.ndarray[float]",
        W: "np.ndarray[np.ndarray[float]]",
    ) -> "np.ndarray[float]":
        """ある層に対する入力ベクトルおよび重み行列から出力ベクトルを計算し，返す．

        >>> x = np.array([0, 1])
        >>> W_AB = np.array([
        ...     [ 1,  2,  3],
        ...     [ 3, -2, -1],
        ... ])
        >>> g_B = MyMLP.g(x, W_AB)
        >>> g_B_expected = np.array([0.95257413, 0.11920292, 0.26894142])
        >>> np.allclose(g_B, g_B_expected)
        True
        >>> W_BC = np.array([
        ...     [ 1,  3],
        ...     [ 2, -2],
        ...     [ 3, -1],
        ... ])
        >>> g_C = MyMLP.g(g_B, W_BC)
        >>> g_C_expected = np.array([0.88056634, 0.91296404])
        >>> np.allclose(g_C, g_C_expected)
        True
        """
        res = x @ W
        res = res.T
        res = sigmoid(res)
        return res

    @classmethod
    def compute_epsilon(
        cls,
        err: "np.ndarray[float]",
        g: "np.ndarray[float]",
    ) -> "np.ndarray[float]":
        """ある層に対する誤差ベクトルおよび出力ベクトルから修正量ベクトルを計算し，返す．

        >>> b = np.array([1, 0])
        >>> g_C = np.array([0.5, 0.5])
        >>> err = g_C - b
        >>> e_C_expected = np.array([-0.125, 0.125])
        >>> np.allclose(MyMLP.compute_epsilon(err, g_C), e_C_expected)
        True
        """
        res = []
        for i in range(len(err)):
          res.append(err[i] * g[i] * (1 - g[i]))
        return np.array(res)

    def update_W(
        self,
        W: "np.ndarray[np.ndarray[float]]",
        x: "np.ndarray[float]",
        e: "np.ndarray[float]",
    ) -> "np.ndarray[np.ndarray[float]]":
        """ある層に対する重み行列，入力ベクトル，および修正量ベクトルから更新後の重み行列を計算し，返す．

        >>> model = MyMLP()
        >>> W_BC = np.array([
        ...     [ 1,  3],
        ...     [ 2, -2],
        ...     [ 3, -1],
        ... ])
        >>> g_B = np.array([0.5, 0.5, 0.5])
        >>> e_C = np.array([-0.125, 0.125])
        >>> W_BC_expected = np.array([
        ...     [ 1.0625,  2.9375],
        ...     [ 2.0625, -2.0625],
        ...     [ 3.0625, -1.0625],
        ... ])
        >>> np.allclose(model.update_W(W_BC, g_B, e_C), W_BC_expected)
        True
        """
        res = W - self.rho * np.outer(x, e)
        return res

    def fit(
        self,
        X_train: "np.ndarray[np.ndarray[float]]",
        y_train: "np.ndarray[int]",
    ) -> None:
        """誤差逆伝播法に基づき，多層パーセプトロンの各層の重みを学習する．"""

        # 前準備
        n = len(X_train)  # 入力パターンの総数
        d = len(X_train[0])  # 入力ベクトルの次元数
        c = len(np.unique(y_train))  # クラス数

        # 訓練データを学習に適した形に加工
        X_train_ext = extend(X_train)
        y_one_hot = to_one_hot(y_train, c)

        # ---------------------------------------------------------------------#
        # 1. 各層間の重みを標準正規分布に従う乱数で初期化
        # ---------------------------------------------------------------------#
        rng = np.random.default_rng(self.random_seed)
        self.W_AB = rng.standard_normal((d + 1, self.hidden_unit_size))
        self.W_BC = rng.standard_normal((self.hidden_unit_size, c))

        while True:  # 学習が収束するまで繰り返し
            # -----------------------------------------------------------------#
            # 2. 特徴ベクトルを一つずつ取り出し学習
            # -----------------------------------------------------------------#
            total_err = 0  # 誤差の総和を初期化
            for i, x_train in enumerate(X_train_ext):
                b_i = y_one_hot[i]

                # -------------------------------------------------------------#
                # 2-1. 順伝搬
                # -------------------------------------------------------------#
                # 順伝搬により各層の出力を計算
                g_B = MyMLP.g(x_train, self.W_AB)
                g_C = MyMLP.g(g_B, self.W_BC)

                # 出力層の出力と教師信号の差を計算し，誤差の総和を加算
                err = g_C - b_i  # 出力層（C層）の出力をg_Cで表すと想定
                total_err += (err**2).sum() / 2

                # -------------------------------------------------------------#
                # 2-2. 逆伝搬
                # -------------------------------------------------------------#
                # 各層の修正量を計算
                e_C = MyMLP.compute_epsilon(err, g_C)
                e_B = MyMLP.compute_epsilon(self.W_BC @ e_C, g_B)

                # 各層の重みを更新
                self.W_AB = MyMLP.update_W(self, self.W_AB, x_train, e_B)
                self.W_BC = MyMLP.update_W(self, self.W_BC, g_B, e_C)

            # -----------------------------------------------------------------#
            # 3. 収束判定
            # -----------------------------------------------------------------#
            # 1パターンあたりの誤差を計算し，しきい値未満であれば学習終了
            avg_loss = total_err / n
            # print(avg_loss) # 収束の様子を確認したい場合はコメントを外す
            if avg_loss < self.loss_threshold:
                break

    def predict(
        self,
        test_X: "np.ndarray[np.ndarray[float]]",
    ) -> "np.ndarray[int]":
        """多層パーセプトロンを用いて与えられた各特徴ベクトルが属するクラスを予測し，返す．"""
        # 特徴ベクトルを拡張ベクトルに変換
        test_X_ext = extend(test_X)

        # 各特徴ベクトルに対し順伝搬を行い，最大値選択機によってクラスを予測
        res = []
        for i, x_test in enumerate(test_X_ext):
          g_B = MyMLP.g(x_test, self.W_AB)
          g_C = MyMLP.g(g_B, self.W_BC)
          a = g_C[0]
          m = 0
          for j in range(len(g_C)):
            if a < g_C[j]:
              a = g_C[j]
              m = j
          res.append(m)
        return np.array(res)


