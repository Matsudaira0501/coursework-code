class MyKL:
    def __init__(
        self,
        n_components: int = 2,
    ):
        self.n_components = n_components
        self.A = None

    def fit(
        self,
        X_train: "np.ndarray[np.ndarray[float]]",
    ) -> "np.ndarray[np.ndarray[float]]":
        """分散最大基準に基づき，変換行列を学習する．"""

        # 特徴ベクトルの総数を取得
        n = len(X_train)

        # 特徴ベクトルの分散共分散行列を計算
        cov = compute_S(X_train, np.mean(X_train, axis=0))
        cov = cov / n

        # 分散共分散行列から固有値及び固有値ベクトルを計算し，固有値の大きい順に整列
        eigenvalues, eigenvectors = compute_sorted_eigen(cov)

        # 上位n_components個の固有値ベクトルを変換行列として抽出
        self.A = eigenvectors[0:self.n_components]

        return self.A

    def transform(
        self,
        X_test: "np.ndarray[np.ndarray[float]]",
    ) -> "np.ndarray[np.ndarray[float]]":
        """学習した変換行列によって特徴量ベクトルを射影する．"""

        return X_test @ (self.A).T