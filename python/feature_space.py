def compute_w(
    S_w: "np.ndarray[np.ndarray[float]]",
    means_0: "np.ndarray[float]",
    means_1: "np.ndarray[float]",
) -> "np.ndarray[float]":
    """クラス内変動行列および各クラスの期待値ベクトルから線形変換ベクトルを計算し，正規化して返す．
    >>> means_0 = np.array([2.2, 1.8, 1.6])
    >>> means_1 = np.array([1.8, 1.0, 0.4])
    >>> S_w = np.array([[13.6, -4.8, -9.2],
    ...                 [-4.8, 16.8, -2.4],
    ...                 [-9.2, -2.4, 18.4]])
    >>> w = compute_w(S_w, means_0, means_1)
    >>> np.allclose(w, np.array([0.66370279, 0.43623657, 0.60761523]))
    True
    """
    res = np.linalg.inv(S_w) @ (means_0 - means_1)
    c = np.linalg.norm(res, ord=2)
    return res / c


