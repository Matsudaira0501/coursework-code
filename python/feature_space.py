class MyFisher:
    def __init__(self):
        self.w = None  # 1次元空間への変換ベクトル

    def fit(
        self,
        X_train: "np.ndarray[np.ndarray[float]]",
        y_train: "np.ndarray[float]",
    ) -> "np.ndarray[float]":
        """クラス内変動・クラス間変動比を最大にする変換ベクトルを学習し，各クラスの変換後の重心を保持する．"""

        # 訓練データをクラス毎に分けその期待値ベクトルを計算
        X_train_0 = X_train[y_train == 0]
        X_train_1 = X_train[y_train == 1]
        means_0 = X_train_0.mean(axis=0)
        means_1 = X_train_1.mean(axis=0)

        # クラス内変動行列を計算
        S_w = compute_S(X_train, np.mean(X_train))

        # 各期待値ベクトル及びクラス内変動行列から正規化した変換ベクトルを計算
        self.w = compute_w(S_w, means_0, means_1)

        return self.w

    def transform(
        self,
        X_test: "np.ndarray[np.ndarray[float]]",
    ) -> "np.ndarray[float]":
        """学習した変換ベクトルによって特徴量ベクトルを射影する．"""

        return X_test @ self.w

from typing import Tuple


def compute_sorted_eigen(
    cov_matrix: "np.ndarray[np.ndarray[float]]",
) -> Tuple["np.ndarray[float]", "np.ndarray[np.ndarray[float]]"]:
    """分散共分散行列から固有値および固有ベクトルを計算し，それぞれ固有値の降順に並べて返す．
    >>> cov = np.array([[2.0,  1.0,  1.0],
    ...                 [1.0,  3.0, -1.0],
    ...                 [1.0, -1.0,  2.0]])
    >>> eigenvalues, eigenvectors = compute_sorted_eigen(cov)
    >>> np.allclose(eigenvalues, np.array([3.73205081, 3., 0.26794919]))
    True
    >>> np.allclose(
    ...     eigenvectors,
    ...     np.array([[-3.25057584e-01, -8.88073834e-01,  3.25057584e-01],
    ...               [-7.07106781e-01, -2.56839179e-16, -7.07106781e-01],
    ...               [ 6.27963030e-01, -4.59700843e-01, -6.27963030e-01]])
    ... )
    True
    """
    eigenvalues, eigenvectors = np.linalg.eig(cov_matrix)
    idx = np.argsort(-eigenvalues)
    return eigenvalues[idx], eigenvectors.T[idx]


