import numpy as np

def compute_S(
    X: "np.ndarray[np.ndarray[float]]",
    means: "np.ndarray[float]",
) -> "np.ndarray[np.ndarray[float]]":
    """観測値ベクトルの集合およびその期待値ベクトルから変動行列を計算し，返す．
    >>> X = np.array([
    ...    [1, 2, 3],
    ...    [3, 1, 2],
    ...    [2, 3, 1],
    ...    [3, 2, 1],
    ...    [2, 1, 1],
    ... ], dtype=float)
    >>> compute_S(X, X.mean(axis=0))
    array([[ 2.8, -0.8, -1.6],
           [-0.8,  2.8, -0.4],
           [-1.6, -0.4,  3.2]])
    """
    A = X - means
    return A.T @ A


